/**
 * Contents of the generated `#build/smile/*` modules and their type
 * declarations.
 */
import type { ColumnSummary } from "../builder/column";
import type { SmileConfig } from "../builder/config";
import type { ScanResult } from "./scanner";
import type { LoadedStimuli } from "./stimuli";

// ─── Timeline module ─────────────────────────────────────────────────────────

/** JavaScript source of `#build/smile/timeline`. */
export function timelineModuleContents(scan: ScanResult | null): string {
  const experimentName = scan?.experimentName ?? null;
  const entries = scan?.entries ?? [];
  const tree = scan?.tree ?? null;
  return [
    "// Generated by the smile module. Do not edit.",
    `export const experimentName = ${JSON.stringify(experimentName)};`,
    `export const entries = ${JSON.stringify(entries, null, 2)};`,
    `export const tree = ${JSON.stringify(tree, null, 2)};`,
    "",
  ].join("\n");
}

/** TypeScript declaration source for `#build/smile/timeline`. */
export function timelineTypesContents(): string {
  return [
    "// Generated by the smile module. Do not edit.",
    'import type { TimelineEntry, TimelineNode } from "#smile/runtime/types";',
    "",
    "export declare const experimentName: string | null;",
    "export declare const entries: TimelineEntry[];",
    "export declare const tree: TimelineNode | null;",
    "",
  ].join("\n");
}

// ─── Stimuli module ──────────────────────────────────────────────────────────

export interface StimuliTemplateInput {
  /** Name of the active experiment's dataset, or null. */
  active: string | null;
  datasets: Record<string, LoadedStimuli>;
}

/** JavaScript source of `#build/smile/stimuli`. */
export function stimuliModuleContents(input: StimuliTemplateInput): string {
  const datasets: Record<string, unknown> = {};
  for (const [name, loaded] of Object.entries(input.datasets)) {
    datasets[name] = {
      name: loaded.name,
      files: loaded.files,
      trialIDColumn: loaded.trialIDColumn,
      rows: loaded.rows,
    };
  }
  return [
    "// Generated by the smile module. Do not edit.",
    `export const active = ${JSON.stringify(input.active)};`,
    `export const datasets = ${JSON.stringify(datasets, null, 2)};`,
    "",
  ].join("\n");
}

// ─── Stimuli types ───────────────────────────────────────────────────────────

function pascalCase(name: string): string {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("");
}

/** TypeScript type text for one column, as it appears after JSON embedding. */
export function columnTypeText(summary: ColumnSummary): string {
  let base: string;
  switch (summary.kind) {
    case "string":
      base = "string";
      break;
    case "number":
      base = "number";
      break;
    case "boolean":
      base = "boolean";
      break;
    case "date":
      // Dates are embedded as ISO strings.
      base = "string";
      break;
    case "enum":
      base = (summary.values ?? []).map((v) => JSON.stringify(v)).join(" | ") || "string";
      break;
    case "json":
      base = "unknown";
      break;
    case "array":
      base = "unknown[]";
      break;
    case "object":
    case "looseObject":
      base = "Record<string, unknown>";
      break;
  }
  if (summary.nullable) base = `${base} | null`;
  return base;
}

/** Interface text for one dataset's rows. */
export function rowInterfaceText(
  interfaceName: string,
  columns: Record<string, ColumnSummary>,
): string {
  const lines = [`export interface ${interfaceName} {`];
  for (const [name, summary] of Object.entries(columns)) {
    const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
    const optional = summary.optional && !summary.hasDefault ? "?" : "";
    lines.push(`  ${key}${optional}: ${columnTypeText(summary)};`);
  }
  lines.push("}");
  return lines.join("\n");
}

/** Name of the generated row interface for a dataset. */
export function rowInterfaceName(datasetName: string): string {
  return `${pascalCase(datasetName)}Row`;
}

/** TypeScript declaration source for `#build/smile/stimuli`. */
export function stimuliTypesContents(config: SmileConfig | null, active: string | null): string {
  const lines: string[] = ["// Generated by the smile module. Do not edit.", ""];
  const seen = new Set<string>();
  const entries: Array<[string, string]> = [];

  for (const experiment of config?.experiments ?? []) {
    const { stimuli } = experiment;
    if (seen.has(stimuli.name)) continue;
    seen.add(stimuli.name);
    const interfaceName = rowInterfaceName(stimuli.name);
    lines.push(rowInterfaceText(interfaceName, stimuli.table.summarizeColumns()), "");
    entries.push([stimuli.name, interfaceName]);
  }

  lines.push("/** Row types keyed by dataset name. */");
  lines.push("export interface StimuliRows {");
  for (const [name, interfaceName] of entries) {
    lines.push(`  ${JSON.stringify(name)}: ${interfaceName};`);
  }
  lines.push("}", "");

  lines.push("/** Name of the active experiment's dataset. */");
  lines.push(`export type ActiveDataset = ${active ? JSON.stringify(active) : "never"};`, "");

  lines.push("export interface EmbeddedDataset<Row> {");
  lines.push("  name: string;");
  lines.push("  files: string[];");
  lines.push("  trialIDColumn: string;");
  lines.push("  rows: Row[];");
  lines.push("}", "");

  lines.push(`export declare const active: ActiveDataset | null;`);
  lines.push(
    "export declare const datasets: { [K in keyof StimuliRows]: EmbeddedDataset<StimuliRows[K]> };",
  );
  lines.push("");
  return lines.join("\n");
}
